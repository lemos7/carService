import { test, expect } from '@playwright/test';
import { newAccount } from './fixtures';
test('cadastro, restauração, logout, login e proteção de rota', async ({ page }) => {
  const account = newAccount();
  await page.goto('/veiculos');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByRole('link', { name: 'Criar uma conta' }).click();
  await page.getByLabel('Nome').fill(account.name);
  await page.getByLabel('E-mail').fill(account.email);
  await page.getByLabel('Senha').fill(account.password);
  await page.getByRole('button', { name: 'Cadastrar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText(`Olá, ${account.name}`)).toBeVisible();
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.goto('/veiculos');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('E-mail').fill(account.email);
  await page.getByLabel('Senha').fill('Incorreta123!');
  const rejected = page.waitForResponse((r) => r.url().endsWith('/api/auth/login'));
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  expect((await rejected).status()).toBe(401);
  await expect(page.getByRole('alert')).toBeVisible();
  await page.getByLabel('Senha').fill(account.password);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Sair', exact: true })).toBeVisible();
  await page.goto('/veiculos');
  await expect(page.getByRole('heading', { name: 'Meus veículos' })).toBeVisible();
});
